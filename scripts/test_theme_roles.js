'use strict';

/**
 * 테마 역할 규칙 단위 검증 — node scripts/test_theme_roles.js
 *
 * 2026-11-24 사용자 지적("#60065: 로봇 테마에서 휴림로봇이 왜 실질 거래대금 대장이냐")으로
 * 정적·동적·스냅샷·저장 스크립트가 제각각이던 역할 규칙을 lib/theme-roles.js 하나로 모았다.
 * 이 파일은 그 규칙이 다시 흐트러지지 않게 11/23 실데이터 케이스와 경계값을 고정한다.
 */
const assert = require('assert');
const { assignThemeRoles, themeRoleMap, pickThemeLeaders } = require('../lib/theme-roles');

const S = (name, code, changePct, valueEok) => ({ name, code, changePct, value: valueEok * 1e8 });
const roles = (list) => list.map((s) => `${s.name}:${s.role}`);

let pass = 0;
function check(label, fn) {
  fn();
  pass += 1;
  console.log('  ✓ ' + label);
}

/* ── 1) 11/23 로봇(산업용/협동로봇 등) 실데이터 ───────────────────────────────
 * KRX 확정(네이버 세션 최종) 대금: 원익홀딩스 1,514.9억 · 에이엘로봇 1,446.5억 ·
 * 빅웨이브로보틱스 1,412.3억 · 휴림로봇 563.5억 → 휴림로봇은 테마 대금 7위다.
 * 예전 코드는 등락률 1위(휴림로봇 +30.00%)에 '실질 거래대금 대장'을 달았다. */
check('로봇: 상승률 대장=휴림로봇, 실질 거래대금 대장=원익홀딩스(1,514.9억)', () => {
  const robot = [
    S('휴림로봇', '090710', 30.0, 563.5),
    S('코스모로보틱스', '439960', 29.97, 322.3),
    S('빅웨이브로보틱스', '0035S0', 17.5, 1412.3),
    S('디케이티', '290550', 11.21, 344.1),
    S('원익홀딩스', '030530', 4.82, 1514.9),
    S('에이엘로봇', '471800', 4.4, 1446.5),
  ];
  const out = assignThemeRoles(robot, 4);
  assert.deepStrictEqual(roles(out), [
    '휴림로봇:상승률 대장',
    '원익홀딩스:실질 거래대금 대장',
    '코스모로보틱스:동반 상승',
    '빅웨이브로보틱스:동반 상승',
  ]);
});

/* ── 2) 지능형로봇/AI 11/23: 상승률 1위 휴림로봇 · 대금 1위(+3%↑) 로보티즈 ── */
check('지능형로봇: 대금 대장=로보티즈(979.4억)', () => {
  const out = assignThemeRoles([
    S('휴림로봇', '090710', 30.0, 563.5),
    S('피앤에스로보틱스', '460940', 9.93, 302.3),
    S('로보티즈', '108490', 6.85, 979.4),
    S('매드업', '0039P0', 6.58, 277.8),
    S('삼성에스디에스', '018260', -14.61, 1511.5),
  ], 4);
  assert.deepStrictEqual(roles(out).slice(0, 3), [
    '휴림로봇:상승률 대장',
    '로보티즈:실질 거래대금 대장',
    '피앤에스로보틱스:동반 상승',
  ]);
});

/* ── 3) 상승률 1위 = +3%↑ 대금 1위 (같은 종목) → '상승률 대장'만, 대금 자리는 비움 ── */
check('태양광 11/23: 금양그린파워가 둘 다 → 대금 대장 자리 비움(2순위에 옮겨 붙이지 않음)', () => {
  const out = assignThemeRoles([
    S('금양그린파워', '282720', 30.0, 217.1),
    S('원익IPS', '240810', 2.59, 654.8),
    S('LS ELECTRIC', '010120', 2.1, 655.2),
  ], 4);
  assert.deepStrictEqual(roles(out), [
    '금양그린파워:상승률 대장',
    '원익IPS:동반 상승',
    'LS ELECTRIC:동반 상승',
  ]);
});

/* ── 3-2) 상승률 1위가 +3%↑ 대금 1위는 아닌데, **두 번째** 대금 종목이 대장이 되면 안 된다 ──
 *  (2026-11-24 로컬 스모크에서 잡힌 실제 사례: 반도체 재료/부품 — 두산 +16.27% 866억이
 *   상승률 1위이면서 대금 1위, 그 밑의 케이씨텍 213억에 '실질 거래대금 대장'이 불어 있었다) */
check('상승률 1위가 대금 1위면 2순위 대금 종목에 대금 대장을 붙이지 않는다', () => {
  const out = assignThemeRoles([
    S('두산', '000150', 16.27, 866),
    S('케이씨텍', '281820', 13.13, 213),
    S('덕산하이메탈', '077360', 13.45, 17),
    S('하나마이크론', '067310', 6.47, 63),
  ], 4);
  assert.deepStrictEqual(roles(out), [
    '두산:상승률 대장',
    '덕산하이메탈:동반 상승',
    '케이씨텍:동반 상승',
    '하나마이크론:동반 상승',
  ]);
  assert.ok(!out.some((s) => s.role === '실질 거래대금 대장'));
});

/* ── 4) +3% 미만 대금 1위는 '대장' 딱지를 달지 않는다 ── */
check('+1.8% 대금 1위(475억)는 대금 대장이 아니다', () => {
  const out = assignThemeRoles([
    S('A', '000001', 1.8, 475),
    S('B', '000002', 5.0, 100),
    S('C', '000003', 2.0, 300),
  ], 4);
  assert.ok(!out.some((s) => s.role === '실질 거래대금 대장'));
  assert.strictEqual(out[0].name, 'B');
  assert.strictEqual(out[0].role, '상승률 대장');
});

/* ── 5) ±100% 이상 이상치는 타일에서도 뺀다 ── */
check('+180% 신규상장 종목은 상승률 대장이 되지 않는다', () => {
  const { pctLeader } = pickThemeLeaders([
    S('신규상장', '999999', 180.0, 1000),
    S('D', '000004', 5.0, 120),
  ]);
  assert.strictEqual(pctLeader.name, 'D');
});

/* ── 6) 하락만 있는 테마: 대장 없음, 하락 대금 상위로만 ── */
check('하락 테마에서 하락 종목이 상승률 대장이 되지 않는다', () => {
  const out = assignThemeRoles([
    S('X', '000005', -3.0, 500),
    S('Y', '000006', -1.0, 100),
  ], 4);
  assert.deepStrictEqual(roles(out), ['X:하락 대금 상위', 'Y:하락 대금 상위']);
});

/* ── 7) 스냅샷 파일의 잘못된 역할은 화면 직전에 다시 계산된다 ──────────────
 *  카드에 실린 종목으로 다시 계산한다(카드 밖 종목의 대금은 화면이 모른다).
 *  → 스냅샷은 테마 1위(상승률·대금)를 반드시 싣도록 생성되므로(2026-11-24 수리)
 *    고친 뒤에 쓰인 파일은 카드 기준 = 테마 기준이 된다.
 *  아래는 11/23 옛 파일(휴림로봇=대금 대장) 그대로 — 카드 안 대금 1위는 빅웨이브(1,412.3억)다. */
check('themeRoleMap: 11/23 옛 스냅샷(휴림로봇=대금 대장)을 바로잡는다', () => {
  const old = [
    { name: '휴림로봇', code: '090710', changePct: 30.0, value: 563.5e8, role: '실질 거래대금 대장' },
    { name: '코스모로보틱스', code: '439960', changePct: 29.97, value: 322.3e8, role: '상승률 대장' },
    { name: '빅웨이브로보틱스', code: '0035S0', changePct: 17.5, value: 1412.3e8, role: '동반 상승' },
    { name: '디케이티', code: '290550', changePct: 11.21, value: 344.1e8, role: '동반 상승' },
  ];
  const map = themeRoleMap(old);
  assert.strictEqual(map['090710'], '상승률 대장');
  assert.strictEqual(map['439960'], '동반 상승');
  assert.strictEqual(map['0035S0'], '실질 거래대금 대장'); // 카드 안 대금 1위(1,412.3억 · +17.50%)
  assert.strictEqual(map['290550'], '동반 상승');
});

console.log(`\n테마 역할 규칙 ${pass}건 통과 — lib/theme-roles.js`);
